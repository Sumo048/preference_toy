"""Markdown tables from results/all_runs.csv -> results/report_tables.md.

Every comparison against B1 / B0 is seed-paired: same base policy, same eval noises,
same edit set; the unit of replication is the seed (n = 5 per cell).
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import numpy as np
import pandas as pd

from toypref.arms import ARMS
from toypref.config import ROOT

RES = os.environ.get("TOYPREF_RESULTS", os.path.join(ROOT, "results"))
COLS = [  # (column, label, direction: +1 = higher is better, -1 = lower is better)
    ("neg_mass_ratio", "forget ratio", -1),
    ("neg_noise_to_retain", "neg->retain", +1),
    ("train_neg_still_in_forget", "train neg kept", -1),
    ("retain_tv", "retain TV", -1),
    ("retain_noise_flip", "retain flips", -1),
    ("mass_off", "off mass", -1),
    ("retain_n_below_0.5", "modes <50%", -1),
    ("logp_delta_forget_mean", "dlogp forget", -1),
    ("logp_delta_retain_mean", "dlogp retain", +1),
    ("tv_to_ideal", "TV to ideal", -1),
]


def fmt(v, digits=3):
    return "" if pd.isna(v) else f"{v:.{digits}f}"


def table(df, cols, idx="arm"):
    head = "| " + idx + " | " + " | ".join(lbl for _, lbl, _ in cols) + " |"
    sep = "|---" * (len(cols) + 1) + "|"
    lines = [head, sep]
    for name, row in df.iterrows():
        lines.append(f"| {name} | " + " | ".join(fmt(row.get(c)) for c, _, _ in cols) + " |")
    return "\n".join(lines)


def paired(df, a, b, metric):
    """Mean and sem over (seed, n_forget, n_neg) cells of arm a minus arm b."""
    x = df[df.arm == a].set_index(["seed", "n_forget", "n_neg"])[metric]
    y = df[df.arm == b].set_index(["seed", "n_forget", "n_neg"])[metric]
    d = (x - y).dropna()
    return d.mean(), d.sem(), len(d)


def main():
    df = pd.read_csv(os.path.join(RES, "all_runs.csv"))
    order = [a for a in ARMS if a in set(df.arm)]
    out = ["# Report tables (auto-generated by scripts/report.py)", ""]
    out.append(f"{len(df)} runs, {df.arm.nunique()} arms, {df.cell.nunique()} cells, "
               f"seeds {sorted(df.seed.unique())}.\n")

    out.append("## 1. Every arm, averaged over all cells and seeds\n")
    g = df.groupby("arm")[[c for c, _, _ in COLS]].mean().reindex(order)
    out.append(table(g, COLS))

    for k in sorted(df.n_forget.unique()):
        out.append(f"\n## 2.{k} n_forget = {k}: forget ratio / retain TV by n_neg (seed mean)\n")
        d = df[df.n_forget == k]
        p1 = d.pivot_table(index="arm", columns="n_neg", values="neg_mass_ratio", aggfunc="mean").reindex(order)
        p2 = d.pivot_table(index="arm", columns="n_neg", values="retain_tv", aggfunc="mean").reindex(order)
        ns = list(p1.columns)
        out.append("| arm | " + " | ".join(f"n={n}" for n in ns) + " |")
        out.append("|---" * (len(ns) + 1) + "|")
        for a in order:
            out.append(f"| {a} | " + " | ".join(f"{p1.loc[a, n]:.2f} / {p2.loc[a, n]:.2f}" for n in ns) + " |")

    out.append("\n## 3. Seed-paired differences vs B1_filtered and vs B0 (all cells pooled)\n")
    out.append("mean (sem) of arm minus reference; n = cells x seeds.\n")
    mets = [("neg_mass_ratio", "forget ratio"), ("retain_tv", "retain TV"),
            ("retain_noise_flip", "retain flips"), ("mass_off", "off mass")]
    out.append("| arm | " + " | ".join(f"{l} - B1" for _, l in mets) + " | " +
               " | ".join(f"{l} - B0" for _, l in mets[1:]) + " |")
    out.append("|---" * (1 + 2 * len(mets) - 1) + "|")
    for a in order:
        cells = []
        for m, _ in mets:
            mu, se, _ = paired(df, a, "B1_filtered", m)
            cells.append(f"{mu:+.3f} ({se:.3f})")
        for m, _ in mets[1:]:
            mu, se, _ = paired(df, a, "B0_frozen", m)
            cells.append(f"{mu:+.3f} ({se:.3f})")
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out.append("\n## 4. Per-cell wins over B1 (both axes)\n")
    out.append("Cells (of n_forget x n_neg) where the seed-mean forget ratio is lower than B1's by more "
               "than 2 paired sem AND the seed-mean retain TV is not higher than B1's by more than 2 paired sem.\n")
    keyed = df.set_index(["arm", "n_forget", "n_neg", "seed"])
    wins = []
    for a in order:
        n_win, n_cells, where = 0, 0, []
        for (k, n), _ in df[df.arm == a].groupby(["n_forget", "n_neg"]):
            try:
                x = keyed.loc[(a, k, n)]
                y = keyed.loc[("B1_filtered", k, n)]
            except KeyError:
                continue
            n_cells += 1
            df_ = (x.neg_mass_ratio - y.neg_mass_ratio).dropna()
            dt_ = (x.retain_tv - y.retain_tv).dropna()
            if len(df_) < 2:
                continue
            better = df_.mean() < -2 * df_.sem()
            no_worse = dt_.mean() <= 2 * dt_.sem()
            if better and no_worse:
                n_win += 1
                where.append(f"k{k}n{n}")
        wins.append((a, n_win, n_cells, " ".join(where)))
    out.append("| arm | wins | cells | where |\n|---|---|---|---|")
    for a, w, c, wh in wins:
        out.append(f"| {a} | {w} | {c} | {wh} |")

    out.append("\n## 5. Where the forgotten mass goes (from the paired transition matrices)\n")
    out.append("Among eval noises pi_ref sent to a forgotten mode and the arm now sends to a retained mode: "
               "`dest entropy` = entropy of their destination modes / log|R| (1 = spread evenly, 0 = one mode); "
               "`adjacent` = share landing in a ring neighbour of their source mode, vs `chance` = the share an "
               "even spread would give. Mean over all cells and seeds.\n")
    import json
    from toypref.mixture import MixtureConfig
    A = MixtureConfig().adjacency()
    acc = {}
    with open(os.path.join(RES, "extras.jsonl")) as f:
        for line in f:
            e = json.loads(line)
            T = np.asarray(e["extra"]["transition_counts"], dtype=float)
            F = e["forget"]
            R = [m for m in range(A.shape[0]) if m not in F]
            dest = T[np.ix_(F, R)]
            tot = dest.sum()
            if tot < 20:
                continue
            p_ = dest.sum(0) / tot
            ent = float(-(p_[p_ > 0] * np.log(p_[p_ > 0])).sum() / np.log(len(R))) if len(R) > 1 else np.nan
            adj = sum(dest[i, j] for i, f_ in enumerate(F) for j, r in enumerate(R) if A[f_, r]) / tot
            chance = np.mean([A[f_, R].sum() / len(R) for f_ in F])
            acc.setdefault(e["arm"], []).append((ent, adj, chance))
    out.append("| arm | dest entropy | adjacent | chance |\n|---|---|---|---|")
    for a in order:
        if a in acc:
            v = np.nanmean(np.asarray(acc[a]), 0)
            out.append(f"| {a} | {v[0]:.3f} | {v[1]:.3f} | {v[2]:.3f} |")

    with open(os.path.join(RES, "report_tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("->", os.path.join(RES, "report_tables.md"))


if __name__ == "__main__":
    main()
