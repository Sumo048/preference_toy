"""Tables for the two next-step experiments -> results/next_steps/report_tables.md.

Reads results/next_steps/all_runs.csv, produced by
  aggregate.py --cells $RUNS/cells,$RUNS/cells_npos4,$RUNS/cells_npos16,$RUNS/cells_npos64
               --out results/next_steps
Never touches the main results/ outputs.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import numpy as np
import pandas as pd

from toypref.arms import ARMS, FILTERED_ARMS, depends_on_tp
from toypref.config import ROOT

RES = os.environ.get("TOYPREF_NEXT_RESULTS", os.path.join(ROOT, "results", "next_steps"))
PAIRS = [("R_ours_both", "R_ours_filt_both"), ("R_ours_neg", "R_ours_filt_neg"),
         ("R_spread_log_both", "R_spread_filt_log_both"), ("R_spread_log_neg", "R_spread_filt_log_neg"),
         ("R_spread_nhood_both", "R_spread_filt_nhood_both"), ("R_spread_nhood_neg", "R_spread_filt_nhood_neg"),
         ("R_spread_nhood_neg_kl1", "R_spread_filt_nhood_neg_kl1")]
METS = [("neg_mass_ratio", "forget ratio"), ("retain_tv", "retain TV"),
        ("retain_noise_flip", "retain flips"), ("mass_off", "off mass")]
KEY = ["seed", "n_pos", "n_forget", "n_neg"]


def paired(df, a, b, m):
    x = df[df.arm == a].set_index(KEY)[m]
    y = df[df.arm == b].set_index(KEY)[m]
    d = (x - y).dropna()
    return d.mean(), d.sem(), len(d)


def main():
    df = pd.read_csv(os.path.join(RES, "all_runs.csv"))
    out = ["# Next-step tables (auto-generated by scripts/report_next_steps.py)", "",
           f"{len(df)} runs; n_pos levels {sorted(df.n_pos.unique())}; seeds {sorted(df.seed.unique())}.", ""]

    d512 = df[df.n_pos == 512]
    out.append("## 1. Label-filtered vs unfiltered reroute targets (n_pos = 512, all cells)\n")
    out.append("Seed means over all n_forget x n_neg cells; `filt - unfilt` is seed-paired, mean (sem).\n")
    out.append("| unfiltered | filtered | " + " | ".join(f"{l} (unf / filt)" for _, l in METS) + " | "
               + " | ".join(f"d {l}" for _, l in METS[:2]) + " |")
    out.append("|---" * (2 + len(METS) + 2) + "|")
    for u, f in PAIRS:
        if f not in set(d512.arm) or u not in set(d512.arm):
            continue
        cells = []
        for m, _ in METS:
            cells.append(f"{d512[d512.arm == u][m].mean():.3f} / {d512[d512.arm == f][m].mean():.3f}")
        for m, _ in METS[:2]:
            mu, se, n = paired(d512, f, u, m)
            cells.append(f"{mu:+.3f} ({se:.3f})")
        out.append(f"| {u} | {f} | " + " | ".join(cells) + " |")
    b1 = d512[d512.arm == "B1_filtered"]
    if len(b1):
        out.append(f"\nB1_filtered at n_pos=512: forget {b1.neg_mass_ratio.mean():.3f}, retain TV {b1.retain_tv.mean():.3f}.")
    fcols = [c for c in df.columns if c.startswith("rows_filt_")]
    if fcols:
        out.append("\nFallback counters (mean per run): " + ", ".join(
            f"{c[len('rows_filt_'):]} {d512[d512.arm.isin(FILTERED_ARMS)][c].mean():.2f}" for c in fcols))
        out.append(f"Share of filtered targets in a forget mode: "
                   f"{d512[d512.arm.isin(FILTERED_ARMS)].rows_target_frac_in_forget.max():.3f} (max over runs).")

    out.append("\n## 2. n_pos sweep: forget ratio / retain TV by |T_p| (mean over all cells)\n")
    tp = [a for a, s in ARMS.items() if depends_on_tp(s) and a in set(df.arm)]
    ns = sorted(df.n_pos.unique())
    out.append("| arm | " + " | ".join(f"n_pos={n}" for n in ns) + " |")
    out.append("|---" * (len(ns) + 1) + "|")
    g = df.groupby(["arm", "n_pos"])[["neg_mass_ratio", "retain_tv", "mass_off"]].mean()
    for a in tp:
        cells = []
        for n in ns:
            if (a, n) in g.index:
                r = g.loc[(a, n)]
                cells.append(f"{r.neg_mass_ratio:.2f} / {r.retain_tv:.2f}")
            else:
                cells.append("")
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out.append("\n## 3. Off-mode mass by |T_p|\n")
    out.append("| arm | " + " | ".join(f"n_pos={n}" for n in ns) + " |")
    out.append("|---" * (len(ns) + 1) + "|")
    for a in tp:
        out.append(f"| {a} | " + " | ".join(f"{g.loc[(a, n)].mass_off:.3f}" if (a, n) in g.index else ""
                                             for n in ns) + " |")

    out.append("\n## 4. Key arms by n_pos x n_neg (n_forget = 2): forget ratio / retain TV\n")
    key = ["B1_filtered", "B3_npo_b10", "DPO_cpl_b1", "B5_kto_b10", "RM_bon8", "R_ours_both",
           "R_ours_filt_both", "R_spread_filt_nhood_both", "R_spread_nhood_neg_kl1", "R_spread_filt_nhood_neg_kl1"]
    d2 = df[df.n_forget == 2]
    for n_pos in ns:
        dd = d2[d2.n_pos == n_pos]
        if dd.empty:
            continue
        p1 = dd.pivot_table(index="arm", columns="n_neg", values="neg_mass_ratio")
        p2 = dd.pivot_table(index="arm", columns="n_neg", values="retain_tv")
        out.append(f"\n**n_pos = {n_pos}**\n")
        out.append("| arm | " + " | ".join(f"n={c}" for c in p1.columns) + " |")
        out.append("|---" * (len(p1.columns) + 1) + "|")
        for a in key:
            if a in p1.index:
                out.append(f"| {a} | " + " | ".join(f"{p1.loc[a, c]:.2f} / {p2.loc[a, c]:.2f}" for c in p1.columns) + " |")

    with open(os.path.join(RES, "report_tables.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("->", os.path.join(RES, "report_tables.md"))


if __name__ == "__main__":
    main()
